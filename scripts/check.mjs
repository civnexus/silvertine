import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
const root='public';
const html=await readFile(join(root,'index.html'),'utf8');
const css=await readFile(join(root,'styles.css'),'utf8');
const js=await readFile(join(root,'site.js'),'utf8');
const paths=new Set();
for(const m of html.matchAll(/(?:src|href)="(\/[^"#]*)"/g)) paths.add(m[1]);
for(const m of html.matchAll(/srcset="([^"]+)"/g)) for(const item of m[1].split(',')) paths.add(item.trim().split(/\s+/)[0]);
for(const m of css.matchAll(/url\(['"]?(\/[^'")]+)/g)) paths.add(m[1]);
for(const path of paths) if(path!=='/') assert.ok((await stat(join(root,path))).isFile(),`Missing ${path}`);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,'Duplicate IDs');
for(const m of html.matchAll(/href="#([^"]+)"/g)) assert.ok(ids.includes(m[1]),`Broken anchor ${m[1]}`);
assert.equal((html.match(/<h1\b/g)||[]).length,1,'Exactly one h1');
for(const m of html.matchAll(/<img\b[^>]*>/g)) for(const attribute of ['alt','width','height']) assert.match(m[0],new RegExp(`\\b${attribute}=`));
assert.match(html,/<html lang="en">/);
assert.match(html,/name="viewport"/);
assert.match(html,/rel="canonical" href="https:\/\/silvertine.si\/"/);
assert.match(html,/mailto:connect@silvertine.si/);
assert.match(html,/property="og:image:width" content="1200"/);
assert.match(html,/property="og:image:height" content="630"/);
assert.match(html,/name="twitter:card" content="summary_large_image"/);
assert.match(html,/fetchpriority="high"/);
assert.match(css,/prefers-reduced-motion/);
const ld=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(ld.name,'Silvertine');
assert.equal(ld.url,'https://silvertine.si/');
const manifest=JSON.parse(await readFile(join(root,'site.webmanifest'),'utf8'));
for(const icon of manifest.icons) assert.ok((await stat(join(root,icon.src))).isFile());
const config=JSON.parse(await readFile('vercel.json','utf8'));
assert.equal(config.outputDirectory,'dist');
assert.ok(Buffer.byteLength(js)<5000,'Keep client JavaScript under 5 KB');
assert.ok(Buffer.byteLength(css)<24000,'Keep stylesheet under 24 KB');
for(const name of ['summit-960.webp','summit-1280.webp','summit-1680.webp','silvertine-share-branded.jpg']) assert.ok((await stat(join(root,'assets',name))).size<500000,`${name} exceeds image budget`);
console.log(`PASS: ${paths.size} local asset references, all anchors, image accessibility attributes, metadata, structured data, manifest, Vercel config, and performance budgets.`);
